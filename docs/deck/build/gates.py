def gate(section, title, crumb, items, bottom):
    labels = ["들어온 것", "문제", "기준", "확인 방법", "결과", "판단 → 다음"]
    kinds = ["in", None, "q", "do", "out", "end"]
    out = []
    for i, text in enumerate(items):
        it = {"text": text, "label": labels[i]}
        if kinds[i]:
            it["kind"] = kinds[i]
        if kinds[i] == "q":
            it["fs"] = 9.5
        out.append(it)
    return {"kind": "chain", "section": section, "title": title, "crumb": crumb, "perRow": 3, "nodeH": 1.55, "arrowW": 0.9,
            "items": out, "bottom": bottom}


