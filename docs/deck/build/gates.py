# 같은 꼴: [들어온 것] → [문제] → ◇[기준] → [확인 방법] → [결과] → [판단 → 다음]
# 순서도 논리를 장표마다 반복해서, 어느 단계에서 시작해도 "왜 이 단계가 필요하고, 무엇을 넘어야 다음으로 가나"가 보이게 한다

